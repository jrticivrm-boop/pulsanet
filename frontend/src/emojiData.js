const RECENTS_KEY = 'tacticalptx_emoji_recents';

export function loadRecentEmojis() {
  try {
    const raw = localStorage.getItem(RECENTS_KEY);
    const arr = JSON.parse(raw || '[]');
    return Array.isArray(arr) ? arr.filter((e) => typeof e === 'string').slice(0, 48) : [];
  } catch {
    return [];
  }
}

export function pushRecentEmoji(emoji) {
  if (!emoji) return loadRecentEmojis();
  const next = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(0, 48);
  try {
    localStorage.setItem(RECENTS_KEY, JSON.stringify(next));
  } catch {
    /* ignore */
  }
  return next;
}

